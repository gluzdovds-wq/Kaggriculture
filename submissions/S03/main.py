def agent(obs, configuration=None):
    try:
        return _V36_POLICY(obs, configuration)
    except Exception:
        seat = 1 if int(_v36_get(obs, "player", 0) or 0) == 1 else 0
        farms = list(_v36_get(obs, "farms", []) or [])
        farm = farms[seat] if seat < len(farms) else {}
        return {
            "farmer": ["PASS"],
            "hands": [
                ["PASS"] for _ in (_v36_get(farm, "hands", []) or [])
            ],
            "market": [],
        }


def _kaggle_submission_entrypoint(obs, configuration=None):
    return agent(obs, configuration)
